package Linked_list;

import java.util.Vector;

public class VectorExample {
	 public static void main(String[] args) {

	        Vector<String> vector = new Vector<>();

	        vector.add("A");
	        vector.add("B");
	        vector.add("C");

	        System.out.println(vector.get(0));   // Access element
	        System.out.println(vector);          // Print all elements
	    }
}
